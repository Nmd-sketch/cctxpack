#include "format.h"

#include <string.h>

#ifndef CTX_VERSION
#define CTX_VERSION "0.0.0-dev"
#endif

static const char *lang_of(const char *path)
{
    const char *dot = strrchr(path, '.');
    if (!dot || dot == path)
        return "";
    dot++;
    static const struct {
        const char *ext;
        const char *lang;
    } map[] = {
        { "c", "c" },        { "h", "c" },
        { "cc", "cpp" },     { "cpp", "cpp" },
        { "hpp", "cpp" },    { "py", "python" },
        { "js", "javascript" }, { "mjs", "javascript" },
        { "ts", "typescript" }, { "tsx", "tsx" },
        { "jsx", "jsx" },    { "rs", "rust" },
        { "go", "go" },      { "sh", "bash" },
        { "bash", "bash" },  { "ps1", "powershell" },
        { "bat", "batch" },  { "cmd", "batch" },
        { "md", "markdown" }, { "json", "json" },
        { "yml", "yaml" },   { "yaml", "yaml" },
        { "toml", "toml" },  { "ini", "ini" },
        { "cfg", "ini" },    { "html", "html" },
        { "css", "css" },    { "sql", "sql" },
        { "xml", "xml" },    { "java", "java" },
        { "cs", "csharp" },  { "rb", "ruby" },
        { "php", "php" },    { "txt", "text" },
        { "cmake", "cmake" }, { "mk", "make" },
        { "dockerfile", "dockerfile" },
    };
    for (size_t i = 0; i < sizeof(map) / sizeof(map[0]); i++) {
        if (strcmp(dot, map[i].ext) == 0)
            return map[i].lang;
    }
    return "";
}

void format_header(strbuf *b, const char *root_display)
{
    strbuf_appendf(b, "# Context bundle: %s\n", root_display);
    strbuf_appendf(b,
        "<!-- generated by cctxpack %s; token counts are estimates -->\n\n",
        CTX_VERSION);
}

static size_t common_prefix_len(const char *a, const char *b)
{
    size_t i = 0;
    while (a[i] && a[i] == b[i])
        i++;
    return i;
}

static size_t seg_count(const char *p)
{
    size_t n = 0;
    for (size_t i = 0; p[i]; i++) {
        if (p[i] == '/')
            n++;
    }
    return n + 1;
}

static size_t seg_end(const char *p, size_t seg)
{
    size_t i = 0, cur = 0;
    while (p[i]) {
        if (p[i] == '/') {
            if (cur == seg)
                return i;
            cur++;
        }
        i++;
    }
    return i;
}

void format_tree(strbuf *b, char *const *paths, size_t n)
{
    if (n == 0)
        return;
    strbuf_append(b, "```text\n");
    unsigned char is_last[64];
    const char *prev = "";
    for (size_t i = 0; i < n; i++) {
        const char *path = paths[i];
        size_t segs = seg_count(path);
        size_t shared = 0;
        if (i > 0) {
            size_t cp = common_prefix_len(prev, path);
            for (size_t s = 0; s < seg_count(prev); s++) {
                if (seg_end(prev, s) < cp)
                    shared = s + 1;
            }
            if (shared > segs)
                shared = segs;
        }
        const char *next = (i + 1 < n) ? paths[i + 1] : NULL;
        for (size_t s = shared; s < segs; s++) {
            size_t start = 0;
            for (size_t k = 0; k < s; k++)
                start = seg_end(path, k) + 1;
            size_t end = seg_end(path, s);
            int last = 1;
            if (next && strlen(next) > end && strncmp(next, path, end) == 0
                && next[end] == '/')
                last = 0;
            if (s < sizeof(is_last))
                is_last[s] = (unsigned char)last;
            for (size_t d = 0; d < s; d++) {
                strbuf_append(b,
                    (d < sizeof(is_last) && is_last[d]) ? "   " : "|  ");
            }
            strbuf_append(b, "+-- ");
            strbuf_appendn(b, path + start, end - start);
            if (s + 1 < segs)
                strbuf_append(b, "/");
            strbuf_append(b, "\n");
        }
        prev = path;
    }
    strbuf_append(b, "```\n\n");
}

static size_t longest_backtick_run(const char *s, size_t len)
{
    size_t best = 0, cur = 0;
    for (size_t i = 0; i < len; i++) {
        if (s[i] == '`') {
            cur++;
            if (cur > best)
                best = cur;
        } else {
            cur = 0;
        }
    }
    return best;
}

void format_section(strbuf *b, const char *path, const char *content,
    size_t len)
{
    strbuf_appendf(b, "### %s\n", path);
    size_t runs = longest_backtick_run(content, len);
    size_t fence = runs >= 3 ? runs + 1 : 3;
    for (size_t i = 0; i < fence; i++)
        strbuf_append(b, "`");
    strbuf_append(b, lang_of(path));
    strbuf_append(b, "\n");
    strbuf_appendn(b, content, len);
    if (len > 0 && content[len - 1] != '\n')
        strbuf_append(b, "\n");
    for (size_t i = 0; i < fence; i++)
        strbuf_append(b, "`");
    strbuf_append(b, "\n\n");
}

void format_binary(strbuf *b, const char *path, size_t size)
{
    strbuf_appendf(b, "### %s\n", path);
    strbuf_appendf(b, "`«binary: %s (%zu bytes)»`\n\n", path, size);
}
