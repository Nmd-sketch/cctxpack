#ifndef CTX_VERSION
#define CTX_VERSION "0.0.0-dev"
#endif

static const char *lang_of(const char *path)
{
    const char *dot = strrchr(path, '.');
    if (!dot || dot == path)
        return "";
    dot++;
    static const struct {
        const char *ext;
        const char *lang;
    } map[] = {
        { "c", "c" },        { "h", "c" },
        { "cc", "cpp" },     { "cpp", "cpp" },
        { "hpp", "cpp" },    { "py", "python" },
        { "js", "javascript" }, { "mjs", "javascript" },
        { "ts", "typescript" }, { "tsx", "tsx" },
        { "jsx", "jsx" },    { "rs", "rust" },
        { "go", "go" },      { "sh", "bash" },
        { "bash", "bash" },  { "ps1", "powershell" },
        { "bat", "batch" },  { "cmd", "batch" },
        { "md", "markdown" }, { "json", "json" },
        { "yml", "yaml" },   { "yaml", "yaml" },
        { "toml", "toml" },  { "ini", "ini" },
        { "cfg", "ini" },    { "html", "html" },
        { "css", "css" },    { "sql", "sql" },
        { "xml", "xml" },    { "java", "java" },
        { "cs", "csharp" },  { "rb", "ruby" },
        { "php", "php" },    { "txt", "text" },
        { "cmake", "cmake" }, { "mk", "make" },
        { "dockerfile", "dockerfile" },
    };
    for (size_t i = 0; i < sizeof(map) / sizeof(map[0]); i++) {
        if (strcmp(dot, map[i].ext) == 0)
            return map[i].lang;
    }
    return "";
}

const char *format_name(int fmt)
{
    switch (fmt) {
    case FMT_XML:
        return "xml";
    case FMT_JSON:
        return "json";
    case FMT_TXT:
        return "txt";
    default:
        return "md";
    }
}

int format_parse(const char *s)
{
    if (strcmp(s, "md") == 0)
        return FMT_MD;
    if (strcmp(s, "xml") == 0)
        return FMT_XML;
    if (strcmp(s, "json") == 0)
        return FMT_JSON;
    if (strcmp(s, "txt") == 0)
        return FMT_TXT;
    return -1;
}

/* XML text/attribute escape.  Control bytes are passed through unchanged. */
static void append_xml_escaped(strbuf *b, const char *s, size_t n)
{
    for (size_t i = 0; i < n; i++) {
        switch (s[i]) {
        case '&':
            strbuf_append(b, "&amp;");
            break;
        case '<':
            strbuf_append(b, "&lt;");
            break;
        case '>':
            strbuf_append(b, "&gt;");
            break;
        case '"':
            strbuf_append(b, "&quot;");
            break;
        case '\'':
            strbuf_append(b, "&apos;");
            break;
        default:
            strbuf_appendn(b, s + i, 1);
            break;
        }
    }
}

/* JSON string literal via cJSON, so escaping follows the vendored library. */
static void append_json_string(strbuf *b, const char *s)
{
    cJSON *j = cJSON_CreateString(s);
    if (!j)
        return;
    char *p = cJSON_PrintUnformatted(j);
    if (p) {
        strbuf_append(b, p);
        free(p);
    }
    cJSON_Delete(j);
}

void format_open(strbuf *b, const char *root_display, int fmt,
    const format_manifest *man)
{
    char commit[16];
    const char *c = man && man->commit ? man->commit : "unversioned";
    /* defensive: never let a long value break the surrounding markup */
    size_t cn = strlen(c);
    if (cn >= sizeof(commit)) {
        memcpy(commit, c, sizeof(commit) - 1);
        commit[sizeof(commit) - 1] = '\0';
        c = commit;
    }
    switch (fmt) {
    case FMT_XML:
        strbuf_append(b, "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                         "<context root=\"");
        append_xml_escaped(b, root_display, strlen(root_display));
        strbuf_appendf(b, "\" version=\"%s\" commit=\"%s\" files=\"%zu\" "
                           "bytes=\"%zu\" tokens=\"%zu\" digest=\"%016llx\">\n",
            CTX_VERSION, c, man ? man->files : 0, man ? man->bytes : 0,
            man ? man->tokens : 0, man ? man->digest : 0);
        break;
    case FMT_JSON:
        strbuf_append(b, "{\"root\":");
        append_json_string(b, root_display);
        strbuf_appendf(b, ",\"version\":\"%s\",\"manifest\":{\"commit\":\"%s\","
                           "\"files\":%zu,\"bytes\":%zu,\"tokens\":%zu,"
                           "\"digest\":\"%016llx\"},\"tree\":",
            CTX_VERSION, c, man ? man->files : 0, man ? man->bytes : 0,
            man ? man->tokens : 0, man ? man->digest : 0);
        break;
    case FMT_TXT:
        strbuf_appendf(b, "cctxpack bundle: %s (cctxpack %s)\n"
            "manifest: commit %s  files %zu  bytes %zu  tokens %zu  "
            "digest %016llx\n\n",
            root_display, CTX_VERSION, c, man ? man->files : 0,
            man ? man->bytes : 0, man ? man->tokens : 0,
            man ? man->digest : 0);
        break;
    default:
        strbuf_appendf(b, "# Context bundle: %s\n", root_display);
        strbuf_appendf(b,
            "<!-- generated by cctxpack %s; token counts are estimates -->\n",
            CTX_VERSION);
        /* Machine-greppable and invisible when rendered. */
        strbuf_appendf(b,
            "<!-- cctxpack-manifest commit=%s files=%zu bytes=%zu tokens=%zu "
            "digest=%016llx -->\n\n",
            c, man ? man->files : 0, man ? man->bytes : 0,
            man ? man->tokens : 0, man ? man->digest : 0);
        break;
    }
}

static size_t common_prefix_len(const char *a, const char *b)
{
    size_t i = 0;
    while (a[i] && a[i] == b[i])
        i++;
    return i;
}

static size_t seg_count(const char *p)
{
    size_t n = 0;
    for (size_t i = 0; p[i]; i++) {
        if (p[i] == '/')
            n++;
    }
    return n + 1;
}

static size_t seg_end(const char *p, size_t seg)
{
    size_t i = 0, cur = 0;
    while (p[i]) {
        if (p[i] == '/') {
            if (cur == seg)
                return i;
            cur++;
        }
        i++;
    }
    return i;
}

/* ASCII-connector tree, one line per path segment. */
static void tree_lines(strbuf *b, char *const *paths, size_t n)
{
    unsigned char is_last[64];
    const char *prev = "";
    for (size_t i = 0; i < n; i++) {
        const char *path = paths[i];
        size_t segs = seg_count(path);
        size_t shared = 0;
        if (i > 0) {
            size_t cp = common_prefix_len(prev, path);
            for (size_t s = 0; s < seg_count(prev); s++) {
                if (seg_end(prev, s) < cp)
                    shared = s + 1;
            }
            if (shared > segs)
                shared = segs;
        }
        const char *next = (i + 1 < n) ? paths[i + 1] : NULL;
        for (size_t s = shared; s < segs; s++) {
            size_t start = 0;
            for (size_t k = 0; k < s; k++)
                start = seg_end(path, k) + 1;
            size_t end = seg_end(path, s);
            int last = 1;
            if (next && strlen(next) > end && strncmp(next, path, end) == 0
                && next[end] == '/')
                last = 0;
            if (s < sizeof(is_last))
                is_last[s] = (unsigned char)last;
            for (size_t d = 0; d < s; d++) {
                strbuf_append(b,
                    (d < sizeof(is_last) && is_last[d]) ? "   " : "|  ");
            }
            strbuf_append(b, "+-- ");
            strbuf_appendn(b, path + start, end - start);
            if (s + 1 < segs)
                strbuf_append(b, "/");
            strbuf_append(b, "\n");
        }
        prev = path;
    }
}

void format_tree(strbuf *b, char *const *paths, size_t n, int fmt)
{
    if (fmt == FMT_JSON) {
        /* Always called, even when the tree is suppressed: format_open has
         * already written the "tree" key and nothing may follow it.  An empty
         * list renders as [], which is what --no-tree means for a consumer. */
        cJSON *arr = cJSON_CreateArray();
        if (!arr)
            return;
        for (size_t i = 0; i < n; i++)
            cJSON_AddItemToArray(arr, cJSON_CreateString(paths[i]));
        char *p = cJSON_PrintUnformatted(arr);
        if (p) {
            strbuf_append(b, p);
            free(p);
        }
        cJSON_Delete(arr);
        return;
    }
    if (n == 0)
        return;
    strbuf lines;
    strbuf_init(&lines);
    tree_lines(&lines, paths, n);
    switch (fmt) {
    case FMT_XML:
        strbuf_append(b, "<tree>\n");
        append_xml_escaped(b, lines.data, lines.len);
        strbuf_append(b, "</tree>\n");
        break;
    case FMT_TXT:
        strbuf_appendn(b, lines.data, lines.len);
        strbuf_append(b, "\n");
        break;
    default:
        strbuf_append(b, "```text\n");
        strbuf_appendn(b, lines.data, lines.len);
        strbuf_append(b, "```\n\n");
        break;
    }
    strbuf_free(&lines);
}

void format_files_open(strbuf *b, int fmt)
{
    if (fmt == FMT_JSON)
        strbuf_append(b, ",\"files\":[");
}

/* Print a JSON object, prefixing the array separator unless it is the first. */
static void json_object(strbuf *b, int first, cJSON *obj)
{
    if (!obj)
        return;
    char *p = cJSON_PrintUnformatted(obj);
    if (!first)
        strbuf_append(b, ",");
    if (p) {
        strbuf_append(b, p);
        free(p);
    }
    cJSON_Delete(obj);
}

static size_t longest_backtick_run(const char *s, size_t len)
{
    size_t best = 0, cur = 0;
    for (size_t i = 0; i < len; i++) {
        if (s[i] == '`') {
            cur++;
            if (cur > best)
                best = cur;
        } else {
            cur = 0;
        }
    }
    return best;
}

void format_section(strbuf *b, int fmt, int first, const char *path,
    const char *content, size_t len, size_t tokens)
{
    switch (fmt) {
    case FMT_XML:
        if (!first)
            strbuf_append(b, "\n");
        strbuf_append(b, "<file path=\"");
        append_xml_escaped(b, path, strlen(path));
        strbuf_appendf(b, "\" tokens=\"%zu\">\n", tokens);
        append_xml_escaped(b, content, len);
        if (len > 0 && content[len - 1] != '\n')
            strbuf_append(b, "&#10;");
        strbuf_append(b, "</file>\n");
        break;
    case FMT_JSON: {
        cJSON *obj = cJSON_CreateObject();
        if (!obj)
            return;
        cJSON_AddItemToObject(obj, "path", cJSON_CreateString(path));
        cJSON_AddItemToObject(obj, "tokens",
            cJSON_CreateNumber((double)tokens));
        cJSON_AddItemToObject(obj, "content", cJSON_CreateString(content));
        json_object(b, first, obj);
        break;
    }
    case FMT_TXT:
        if (!first)
            strbuf_append(b, "\n");
        strbuf_appendf(b, "===== %s =====\n", path);
        strbuf_appendn(b, content, len);
        if (len > 0 && content[len - 1] != '\n')
            strbuf_append(b, "\n");
        break;
    default:
        strbuf_appendf(b, "### %s\n", path);
        size_t runs = longest_backtick_run(content, len);
        size_t fence = runs >= 3 ? runs + 1 : 3;
        for (size_t i = 0; i < fence; i++)
            strbuf_append(b, "`");
        strbuf_append(b, lang_of(path));
        strbuf_append(b, "\n");
        strbuf_appendn(b, content, len);
        if (len > 0 && content[len - 1] != '\n')
            strbuf_append(b, "\n");
        for (size_t i = 0; i < fence; i++)
            strbuf_append(b, "`");
        strbuf_append(b, "\n\n");
        break;
    }
}

void format_binary(strbuf *b, int fmt, int first, const char *path, size_t size)
{
    switch (fmt) {
    case FMT_XML:
        if (!first)
            strbuf_append(b, "\n");
        strbuf_append(b, "<file path=\"");
        append_xml_escaped(b, path, strlen(path));
        strbuf_appendf(b, "\" binary=\"true\" bytes=\"%zu\"/>\n", size);
        break;
    case FMT_JSON: {
        cJSON *obj = cJSON_CreateObject();
        if (!obj)
            return;
        cJSON_AddItemToObject(obj, "path", cJSON_CreateString(path));
        cJSON_AddItemToObject(obj, "binary", cJSON_CreateTrue());
        cJSON_AddItemToObject(obj, "bytes", cJSON_CreateNumber((double)size));
        json_object(b, first, obj);
        break;
    }
    case FMT_TXT:
        if (!first)
            strbuf_append(b, "\n");
        strbuf_appendf(b, "===== %s =====\n[binary: %s (%zu bytes)]\n", path,
            path, size);
        break;
    default:
        strbuf_appendf(b, "### %s\n", path);
        strbuf_appendf(b, "`«binary: %s (%zu bytes)»`\n\n", path, size);
        break;
    }
}

void format_close(strbuf *b, int fmt)
{
    if (fmt == FMT_JSON)
        strbuf_append(b, "]}\n");
    else if (fmt == FMT_XML)
        strbuf_append(b, "</context>\n");
}
