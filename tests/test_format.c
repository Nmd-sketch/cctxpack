#include "greatest.h"

#include "format.h"
#include "util.h"

#include <string.h>

TEST format_tree_golden(void)
{
    char *paths[] = { "README.md", "docs/a.md", "docs/sub/b.md" };
    strbuf sb;
    strbuf_init(&sb);
    format_tree(&sb, paths, 3);
    ASSERT_STR_EQ("```text\n"
                  "+-- README.md\n"
                  "+-- docs/\n"
                  "|  +-- a.md\n"
                  "|  +-- sub/\n"
                  "|     +-- b.md\n"
                  "```\n\n",
        sb.data);
    strbuf_free(&sb);
    PASS();
}

TEST format_tree_single_file(void)
{
    char *paths[] = { "a/b/c.txt" };
    strbuf sb;
    strbuf_init(&sb);
    format_tree(&sb, paths, 1);
    ASSERT_STR_EQ("```text\n+-- a/\n   +-- b/\n      +-- c.txt\n```\n\n",
        sb.data);
    strbuf_free(&sb);
    PASS();
}

TEST format_section_language_hint(void)
{
    strbuf sb;
    strbuf_init(&sb);
    format_section(&sb, "src/main.c", "int main(void) { return 0; }\n", 29);
    ASSERT_STR_EQ("### src/main.c\n"
                  "```c\n"
                  "int main(void) { return 0; }\n"
                  "```\n\n",
        sb.data);
    strbuf_free(&sb);
    PASS();
}

TEST format_section_extends_fence(void)
{
    strbuf sb;
    strbuf_init(&sb);
    format_section(&sb, "doc.md", "before\n```\ncode\n```\n", 20);
    ASSERT(strstr(sb.data, "````\n") != NULL);
    ASSERT(strncmp(sb.data, "### doc.md\n````markdown\n", 24) == 0);
    strbuf_free(&sb);
    PASS();
}

TEST format_section_adds_trailing_newline(void)
{
    strbuf sb;
    strbuf_init(&sb);
    format_section(&sb, "x.txt", "no-newline", 10);
    ASSERT_STR_EQ("### x.txt\n```text\nno-newline\n```\n\n", sb.data);
    strbuf_free(&sb);
    PASS();
}

TEST format_binary_placeholder(void)
{
    strbuf sb;
    strbuf_init(&sb);
    format_binary(&sb, "data/x.bin", 7);
    ASSERT_STR_EQ("### data/x.bin\n`«binary: data/x.bin (7 bytes)»`\n\n",
        sb.data);
    strbuf_free(&sb);
    PASS();
}

TEST format_header_names_root(void)
{
    strbuf sb;
    strbuf_init(&sb);
    format_header(&sb, "myrepo");
    ASSERT(strncmp(sb.data, "# Context bundle: myrepo\n", 25) == 0);
    ASSERT(strstr(sb.data, "generated by cctxpack") != NULL);
    ASSERT(strstr(sb.data, CTX_VERSION) != NULL);
    strbuf_free(&sb);
    PASS();
}

SUITE(format_suite)
{
    RUN_TEST(format_tree_golden);
    RUN_TEST(format_tree_single_file);
    RUN_TEST(format_section_language_hint);
    RUN_TEST(format_section_extends_fence);
    RUN_TEST(format_section_adds_trailing_newline);
    RUN_TEST(format_binary_placeholder);
    RUN_TEST(format_header_names_root);
}
